/**
 * Retrieves translated string for a key with guaranteed English fallback
 */
export function t(key: TranslationKey, lang: SupportedLanguage = DEFAULT_LANGUAGE): string {
  const langDict = TRANSLATIONS[lang];
  if (langDict && langDict[key]) {
    return langDict[key];
  }
  // Safe English fallback
  return TRANSLATIONS[DEFAULT_LANGUAGE][key] || key;
}

/**
 * Applies document language, direction (LTR vs RTL), and RTL CSS class
 */
export function applyLanguageDirection(lang: SupportedLanguage): void {
  if (typeof document === 'undefined') return;
  const isRtl = isRTLLanguage(lang);
  document.documentElement.lang = lang;
  document.documentElement.dir = isRtl ? 'rtl' : 'ltr';
  if (isRtl) {
    document.documentElement.classList.add('rtl-mode');
  } else {
    document.documentElement.classList.remove('rtl-mode');
  }
}
